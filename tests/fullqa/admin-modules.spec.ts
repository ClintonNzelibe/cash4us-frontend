test('task create and edit with persisted dates and reward',async({page,data})=>{
  await login(page,data)
  await page.goto('/admin/tasks/new')
  await page.getByPlaceholder('Enter task title').fill(`Task QA ${data.key}`)
  await page.getByPlaceholder('Describe what members need to do...').fill('Synthetic task description')
  await page.getByPlaceholder('0.00').fill('2')
  const today=new Date().toISOString().slice(0,10)
  await page.locator('input[type=date]').nth(0).fill(today)
  await page.locator('input[type=date]').nth(1).fill(today)
  await page.locator('button[type=submit]').click()
  await expect(page).not.toHaveURL(/\/new$/)
  const list=await api(page,`/admin/tasks/?search=Task QA ${data.key}`)
  const item=(list.body.results??list.body).find((x:any)=>x.title===`Task QA ${data.key}`)
  expect(item).toBeTruthy()
  await page.goto(`/admin/tasks/${item.id}/edit`)
  await page.getByPlaceholder('Enter task title').fill(`Edited Task ${data.key}`)
  await page.locator('button[type=submit]').click()
  await expect(page).not.toHaveURL(/\/edit$/)
  const detail=await api(page,`/admin/tasks/${item.id}/`)
  expect(detail.body.title).toBe(`Edited Task ${data.key}`)
  expect(Number(detail.body.reward)).toBe(2)
  await page.getByRole('button',{name:'Deactivate',exact:true}).click()
  await expect(page.getByRole('button',{name:'Activate',exact:true})).toBeVisible()
  await page.reload()
  expect((await api(page,`/admin/tasks/${item.id}/`)).body.is_active).toBe(false)
  await page.getByRole('button',{name:'Activate',exact:true}).click()
  await expect(page.getByRole('button',{name:'Deactivate',exact:true})).toBeVisible()
})

