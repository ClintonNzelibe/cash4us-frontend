import {test,expect,login,api,field} from './fixtures'

test('resource create link, edit, and persistence',async({page,data})=>{
  await login(page,data)
  await page.goto('/admin/resources/create')
  await page.getByLabel('Title',{exact:true}).fill(`Resource QA ${data.key}`)
  await page.getByLabel('Description',{exact:true}).fill('Synthetic resource')
  await page.getByLabel('Resource Type').selectOption('LINK')
  await page.getByLabel('External Link').fill('http://127.0.0.1:5180/resources')
  await page.locator('button[type=submit]').click()
  await expect(page).not.toHaveURL(/\/create$/)
  const list=await api(page,`/admin/resources/?search=Resource QA ${data.key}`)
  const item=(list.body.results??list.body).find((x:any)=>x.title===`Resource QA ${data.key}`)
  expect(item).toBeTruthy()
  await page.goto(`/admin/resources/${item.id}/edit`)
  await page.getByLabel('Title',{exact:true}).fill(`Edited Resource ${data.key}`)
  await page.locator('button[type=submit]').click()
  await expect(page).not.toHaveURL(/\/edit$/)
  expect((await api(page,`/admin/resources/${item.id}/`)).body.title).toBe(`Edited Resource ${data.key}`)
})

