import {test,expect,login,loginThroughUI,api,field,API} from './fixtures'

test('member UI login, profile validation, edit, cancel and persisted settings',async({page,data})=>{
  await loginThroughUI(page,data,'member')
  await page.goto('/profile')
  await page.getByRole('button',{name:'Edit Profile',exact:true}).click()
  await field(page,'First Name','')
  await page.getByRole('button',{name:'Save Changes',exact:true}).click()
  await expect(page.getByText('First name is required.')).toBeVisible()
  await field(page,'First Name',`Edited${data.key}`)
  await field(page,'Last Name','Synthetic')
  await page.getByRole('button',{name:'Save Changes',exact:true}).click()
  await expect(page.getByText('Profile updated successfully.')).toBeVisible()
  await expect(page.getByText(`Edited${data.key}`,{exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByText(`Edited${data.key}`,{exact:true})).toBeVisible()
  expect((await api(page,'/users/me/')).body.first_name).toBe(`Edited${data.key}`)
  await page.getByRole('button',{name:'Edit Profile',exact:true}).click()
  await field(page,'First Name','Cancelled change')
  await page.getByRole('button',{name:'Cancel',exact:true}).click()
  expect((await api(page,'/users/me/')).body.first_name).toBe(`Edited${data.key}`)
})

test('member support creation, validation, detail modal and received reply',async({page,data})=>{
  await login(page,data,'member')
  await page.goto('/support')
  await page.getByRole('button',{name:'New Ticket',exact:true}).click()
  await page.getByRole('button',{name:'Submit Ticket',exact:true}).click()
  await expect(page.getByText(/subject.*required|enter.*subject/i)).toBeVisible()
  const subject=`Member ticket ${data.key}`
  await page.getByPlaceholder('What do you need help with?').fill(subject)
  await page.getByPlaceholder('Describe your issue or question...').fill('Synthetic member question')
  await page.getByRole('button',{name:'Submit Ticket',exact:true}).click()
  await expect(page.getByText('Your support ticket has been submitted.')).toBeVisible()
  await page.reload()
  await page.getByRole('button').filter({hasText:subject}).click()
  await expect(page.getByRole('heading',{name:subject,level:3,exact:true})).toBeVisible()
  const list=await api(page,'/v1/support/')
  const item=(list.body.results??list.body).find((x:any)=>x.subject===subject)
  expect(item.message).toBe('Synthetic member question')
  const response=await page.request.post(`${API}/admin/support/${item.id}/reply/`,{headers:{Authorization:`Bearer ${(data.admin as any).access}`},data:{reply:'Synthetic staff answer'}})
  expect(response.status()).toBe(200)
  await page.reload()
  await page.getByRole('button').filter({hasText:subject}).click()
  await expect(page.getByText('Synthetic staff answer',{exact:true})).toBeVisible()
})

test('member notifications open marks read, unread filter and mark all persist',async({page,data})=>{
  await login(page,data,'member')
  await page.goto('/notifications')
  await page.getByRole('button').filter({hasText:`QA notice ${data.key} 0`}).click()
  await expect.poll(async()=> (await api(page,'/v1/notifications/unread-count/')).body.unread_count).toBe(1)
  await page.reload()
  await page.getByRole('button',{name:/^Unread/}).click()
  await expect(page.getByText(`QA notice ${data.key} 0`,{exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Mark all as read',exact:true}).click()
  await expect(page.getByText('No unread notifications',{exact:true})).toBeVisible()
  await page.reload()
  expect((await api(page,'/v1/notifications/unread-count/')).body.unread_count).toBe(0)
})

test('member resource search, type filter, empty state and opening local link',async({page,data})=>{
  await login(page,data,'member')
  await page.goto('/resources')
  await page.getByPlaceholder('Search resources...').fill(`Fixture Resource ${data.key}`)
  await page.locator('select').selectOption('LINK')
  await expect(page.getByText(`Fixture Resource ${data.key}`,{exact:true})).toBeVisible()
  const opened=page.context().waitForEvent('page')
  await page.getByRole('button',{name:'Visit Link',exact:true}).click()
  const popup=await opened
  await expect(popup).toHaveURL('http://127.0.0.1:5180/resources')
  await popup.close()
  await page.getByPlaceholder('Search resources...').fill(`NO_MATCH_${data.key}`)
  await expect(page.getByText(/No resources found/i)).toBeVisible()
})

