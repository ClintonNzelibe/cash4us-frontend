import {test,expect,login,api,field} from './fixtures'

test('admin member search, detail, deactivate and reactivate persist',async({page,data})=>{
  await login(page,data)
  await page.goto('/admin/members')
  await expect(page.getByPlaceholder(/search/i)).toBeVisible({timeout:60_000})
  await page.getByPlaceholder(/search/i).fill(data.member.email)
  await expect(page.getByText(data.member.email,{exact:true}).first()).toBeVisible()
  await page.goto(`/admin/members/${data.member.id}`)
  await page.getByRole('button',{name:'Deactivate Member',exact:true}).click()
  await expect(page.getByRole('button',{name:'Activate Member',exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button',{name:'Activate Member',exact:true})).toBeVisible()
  expect((await api(page,`/admin/members/${data.member.id}/`)).body.is_active).toBe(false)
  await page.getByRole('button',{name:'Activate Member',exact:true}).click()
  await expect(page.getByRole('button',{name:'Deactivate Member',exact:true})).toBeVisible()
})

test('admin package creation, validation, editing and tenure creation',async({page,data})=>{
  await login(page,data)
  await page.goto('/admin/packages')
  await page.getByRole('button',{name:/Create Package|Add Package/}).first().click()
  await page.getByRole('button',{name:'Create Package',exact:true}).last().click()
  await expect(page.getByText(/name.*required/i)).toBeVisible()
  await page.getByPlaceholder('e.g. Gold Package').fill(`Created QA ${data.key}`)
  await page.getByPlaceholder('0.00').fill('100')
  await page.getByPlaceholder('Optional').fill('105')
  await page.getByRole('button',{name:'Create Package',exact:true}).last().click()
  await expect(page.getByText(`Created QA ${data.key}`,{exact:true}).first()).toBeVisible()
  const list=await api(page,`/admin/packages/?search=Created QA ${data.key}`)
  expect(list.status).toBe(200)
  const rows=list.body.results??list.body
  const item=rows.find((x:any)=>x.name===`Created QA ${data.key}`)
  expect(item).toBeTruthy()
  await page.goto(`/admin/packages/${item.id}`)
  await page.getByRole('button',{name:'Edit',exact:true}).first().click()
  await page.getByPlaceholder('e.g. Gold Package').fill(`Updated QA ${data.key}`)
  await page.getByRole('button',{name:'Save Changes',exact:true}).click()
  await page.reload()
  await expect(page.getByRole('heading',{name:`Updated QA ${data.key}`})).toBeVisible()
  await page.getByRole('button',{name:/Add Tenure/}).first().click()
  await page.getByPlaceholder('e.g. 30').fill('30')
  await page.getByPlaceholder('e.g. 5').fill('4')
  await page.getByRole('button',{name:/Add Tenure/}).last().click()
  await page.reload()
  const detail=await api(page,`/admin/packages/${item.id}/`)
  expect(detail.body.tenures.some((t:any)=>t.duration_days===30)).toBe(true)
})

