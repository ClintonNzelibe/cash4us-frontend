test('admin partner create and edit persist',async({page,data})=>{
  await login(page,data)
  await page.goto('/admin/partners/create')
  await page.getByPlaceholder('Enter partner name').fill(`Partner QA ${data.key}`)
  await page.getByPlaceholder('https://example.com').fill('http://127.0.0.1:5180/partners')
  await page.getByPlaceholder('Describe the partner company...').fill('Synthetic partner')
  await page.locator('button[type=submit]').click()
  await expect(page).not.toHaveURL(/\/create$/)
  await page.reload()
  await expect(page.getByText(`Partner QA ${data.key}`,{exact:true}).first()).toBeVisible()
  const list=await api(page,`/admin/partners/?search=Partner QA ${data.key}`)
  const item=(list.body.results??list.body).find((x:any)=>x.name===`Partner QA ${data.key}`)
  await page.goto(`/admin/partners/${item.id}/edit`)
  await page.getByPlaceholder('Enter partner name').fill(`Edited Partner ${data.key}`)
  await page.locator('button[type=submit]').click()
  await expect(page).not.toHaveURL(/\/edit$/)
  expect((await api(page,`/admin/partners/${item.id}/`)).body.name).toBe(`Edited Partner ${data.key}`)
})

