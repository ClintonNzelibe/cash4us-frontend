import {test,expect,login,api} from './fixtures'

test('campaign create, edit and status persist',async({page,data})=>{
  await login(page,data)
  const advertiser=await api(page,'/admin/advertising/advertisers/create/','POST',{name:`QA advertiser ${data.key}`,email:data.member.email,company_name:'Synthetic'})
  expect(advertiser.status).toBe(201)
  await page.goto('/admin/advertising/campaigns/create')
  await page.locator('select').nth(0).selectOption(advertiser.body.id)
  await page.getByPlaceholder('Enter campaign title').fill(`Campaign QA ${data.key}`)
  await page.getByPlaceholder('Describe the campaign').fill('Synthetic campaign')
  await page.getByPlaceholder('https://example.com').fill('http://127.0.0.1:5180')
  await page.locator('button[type=submit]').click()
  await expect(page).not.toHaveURL(/\/create$/)
  const id=page.url().split('/').pop()!
  await page.goto(`/admin/advertising/campaigns/${id}/edit`)
  await page.getByPlaceholder('Enter campaign title').fill(`Edited Campaign ${data.key}`)
  await page.locator('select').nth(1).selectOption('ACTIVE')
  await page.locator('button[type=submit]').click()
  await expect(page).not.toHaveURL(/\/edit$/)
  const item=await api(page,`/admin/advertising/campaigns/${id}/`)
  expect(item.body.title).toBe(`Edited Campaign ${data.key}`)
  expect(item.body.status).toBe('ACTIVE')
})

for(const action of ['confirm','cancel']) test(`advertising revenue create and ${action} persists`,async({page,data})=>{
  await login(page,data)
  await page.goto('/admin/advertising/revenue/create')
  await page.locator('select').first().selectOption('OTHER')
  await page.getByPlaceholder('0.00').fill('0')
  await page.locator('button[type=submit]').click()
  await expect(page.getByText('Revenue amount must be greater than zero.',{exact:true})).toBeVisible()
  await page.getByPlaceholder('0.00').fill('25')
  await page.getByPlaceholder('Payment or revenue reference').fill(`Revenue QA ${data.key}`)
  await page.getByPlaceholder('Additional remarks').fill('Synthetic revenue')
  await page.locator('button[type=submit]').click()
  await expect(page).not.toHaveURL(/\/create$/)
  const id=page.url().split('/').pop()!
  if(action==='confirm') await page.getByRole('button',{name:'Confirm Revenue',exact:true}).click()
  else {
    await page.getByRole('button',{name:'Cancel Revenue',exact:true}).click()
    await page.getByPlaceholder('Reason for cancellation').fill('Synthetic cancellation')
    await page.getByRole('button',{name:'Confirm Cancellation',exact:true}).click()
  }
  await expect(page.getByText(action==='confirm'?'Confirmed':'Cancelled',{exact:true})).toBeVisible()
  await page.reload()
  expect((await api(page,`/admin/advertising/revenue/${id}/`)).body.status).toBe(action==='confirm'?'CONFIRMED':'CANCELLED')
})

test('package and tenure edit, duplicate validation and active toggles',async({page,data})=>{
  await login(page,data)
  await page.goto(`/admin/packages/${data.package}`)
  await page.getByRole('button',{name:'Deactivate',exact:true}).first().click()
  await expect(page.getByRole('button',{name:'Activate',exact:true}).first()).toBeVisible()
  expect((await api(page,`/admin/packages/${data.package}/`)).body.is_active).toBe(false)
  await page.getByRole('button',{name:'Activate',exact:true}).first().click()
  await page.getByTitle('Edit tenure',{exact:true}).click()
  await page.getByPlaceholder('e.g. 30').fill('0')
  await page.getByRole('button',{name:'Save Changes',exact:true}).click()
  expect(await page.getByPlaceholder('e.g. 30').evaluate((input:HTMLInputElement)=>input.validity.rangeUnderflow)).toBe(true)
  expect((await api(page,`/admin/packages/${data.package}/`)).body.tenures[0].duration_days).toBe(30)
  await page.getByPlaceholder('e.g. 30').fill('30')
  await page.getByPlaceholder('e.g. 5').fill('3')
  const savedTenure=page.waitForResponse(r=>r.url().includes('/api/admin/packages/tenures/')&&r.request().method()==='PATCH')
  await page.getByRole('button',{name:'Save Changes',exact:true}).click()
  expect((await savedTenure).status()).toBe(200)
  await expect(page.getByPlaceholder('e.g. 5')).toHaveCount(0)
  await page.reload()
  expect((await api(page,`/admin/packages/${data.package}/`)).body.tenures[0].required_referrals).toBe(3)
  await page.getByTitle('Deactivate',{exact:true}).click()
  await expect(page.getByTitle('Activate',{exact:true})).toBeVisible()
  expect((await api(page,`/admin/packages/${data.package}/`)).body.tenures[0].is_active).toBe(false)
  await page.getByTitle('Activate',{exact:true}).click()
  await expect(page.getByTitle('Deactivate',{exact:true})).toBeVisible()
  const duplicate=await api(page,`/admin/packages/${data.package}/tenures/`,'POST',{duration_days:30,required_referrals:3,is_active:true})
  expect(duplicate.status).toBe(400)
})

