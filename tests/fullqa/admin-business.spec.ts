test('award member grant persists and duplicate is rejected',async({page,data})=>{
  await login(page,data)
  const created=await api(page,'/admin/rewards/awards/create/','POST',{name:`Grant QA ${data.key}`,points_required:10,number_of_winners:1,award_period:'CUSTOM',status:'ACTIVE',is_active:true})
  expect(created.status).toBe(201)
  const id=created.body.id
  await page.goto(`/admin/rewards/awards/${id}`)
  await page.getByRole('button',{name:'Award Member',exact:true}).click()
  await page.getByPlaceholder('Enter member UUID').fill(data.member.id)
  await page.locator('textarea').fill('Synthetic grant')
  await page.getByRole('button',{name:'Grant Award',exact:true}).click()
  await expect(page.getByRole('button',{name:'Grant Award',exact:true})).toHaveCount(0)
  await page.reload()
  const records=await api(page,`/admin/rewards/user-awards/?award_id=${id}`)
  expect((records.body.results??records.body).length).toBe(1)
  const duplicate=await api(page,`/admin/rewards/awards/${id}/award-user/`,'POST',{user_id:data.member.id})
  expect(duplicate.status).toBe(400)
})

test('community revenue allocation, close and distribution persist',async({page,data})=>{
  await login(page,data)
  const revenue=await api(page,'/admin/advertising/revenue/create/','POST',{source:'OTHER',amount:'100',reference:`PoolRevenue-${data.key}`})
  expect(revenue.status).toBe(201)
  const rid=revenue.body.id??revenue.body.revenue?.id
  expect((await api(page,`/admin/advertising/revenue/${rid}/confirm/`,'POST',{})).status).toBe(200)
  const created=await api(page,'/admin/community/create/','POST',{name:`Distribute QA ${data.key}`})
  expect(created.status).toBe(201)
  const id=created.body.id
  await page.goto(`/admin/community/pools/${id}`)
  await page.locator('select').selectOption(rid)
  await page.getByRole('button',{name:'Allocate Revenue',exact:true}).click()
  await expect(page.getByText(`PoolRevenue-${data.key}`,{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Close Pool',exact:true}).first().click()
  await page.getByRole('button',{name:'Close Pool',exact:true}).last().click()
  await expect(page.getByRole('button',{name:'Distribute Pool',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Distribute Pool',exact:true}).first().click()
  await page.getByRole('button',{name:'Distribute Pool',exact:true}).last().click()
  await expect(page.getByRole('button',{name:'Distribute Pool',exact:true})).toHaveCount(0)
  await page.reload()
  const detail=await api(page,`/admin/community/${id}/`)
  expect(detail.body.status).toBe('DISTRIBUTED')
  expect(detail.body.earnings_count).toBeGreaterThan(0)
  expect(detail.body.earnings.every((x:Record<string, unknown>)=>x.status==='PAID')).toBe(true)
})
