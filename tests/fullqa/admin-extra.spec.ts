for(const module of ['members','packages']) test(`${module} search and active/inactive filters`,async({page,data})=>{
  await login(page,data)
  await page.goto(`/admin/${module}`)
  const search=page.getByPlaceholder(/search/i)
  await search.fill(module==='members'?data.member.email:`QA ${data.key}`)
  for(const [label,value] of [['Inactive','false'],['Active','true']]) {
    const response=page.waitForResponse(r=>r.url().includes(`/api/admin/${module}/`)&&r.url().includes(`is_active=${value}`))
    await page.getByRole('button',{name:label,exact:true}).click()
    const actual=await response
    expect(actual.status()).toBe(200)
    const payload=await actual.json()
    expect((payload.results??payload).every((r:any)=>r.is_active===(value==='true'))).toBe(true)
  }
  await search.fill(`NO_MATCH_${data.key}`)
  await expect(page.getByText(/No members found|No packages found/i)).toBeVisible()
})

test('task and submission search filters and detail navigation',async({page,data})=>{
  await login(page,data)
  await page.goto('/admin/tasks')
  const response=page.waitForResponse(r=>r.url().includes('/api/admin/tasks/?')&&r.url().includes(data.key))
  await page.getByPlaceholder('Search task title, description or platform...').fill(data.key)
  expect((await response).status()).toBe(200)
  await expect(page.getByText(`Fixture Task ${data.key}`,{exact:true}).first()).toBeVisible()
  const submissions=page.waitForResponse(r=>r.url().includes('/api/admin/tasks/submissions/?')&&r.url().includes(data.key))
  await page.getByPlaceholder('Search member, email, code or task...').fill(data.key)
  expect((await submissions).status()).toBe(200)
  await page.locator('select').nth(0).selectOption('true')
  await page.locator('select').nth(1).selectOption('PENDING')
  await page.locator('select').nth(2).selectOption('false')
  const details=page.locator(`a[href='/admin/tasks/submissions/${data.submission}']`).filter({visible:true})
  await details.first().click()
  await expect(page).toHaveURL(new RegExp(data.submission+'$'))
})

test('resource document upload, replacement and retained file on metadata edit',async({page,data})=>{
  await login(page,data)
  await page.goto('/admin/resources/create')
  await page.getByLabel('Title',{exact:true}).fill(`Upload QA ${data.key}`)
  await page.getByLabel('Resource Type').selectOption('DOCUMENT')
  await page.getByLabel('Resource File').setInputFiles({name:`qa-${data.key}.txt`,mimeType:'text/plain',buffer:Buffer.from('Synthetic QA document')})
  await page.locator('button[type=submit]').click()
  await expect(page).not.toHaveURL(/\/create$/)
  const id=page.url().split('/').pop()!
  const original=await api(page,`/admin/resources/${id}/`)
  expect(original.body.resource_file).toContain(`qa-${data.key}`)
  await page.goto(`/admin/resources/${id}/edit`)
  await page.getByLabel('Description',{exact:true}).fill('Updated metadata')
  await page.locator('button[type=submit]').click()
  await expect(page).not.toHaveURL(/\/edit$/)
  expect((await api(page,`/admin/resources/${id}/`)).body.resource_file).toBe(original.body.resource_file)
  await page.goto(`/admin/resources/${id}/edit`)
  await page.getByLabel('Resource File').setInputFiles({name:`replacement-${data.key}.txt`,mimeType:'text/plain',buffer:Buffer.from('Synthetic replacement')})
  await page.locator('button[type=submit]').click()
  await expect(page).not.toHaveURL(/\/edit$/)
  expect((await api(page,`/admin/resources/${id}/`)).body.resource_file).toContain(`replacement-${data.key}`)
})
