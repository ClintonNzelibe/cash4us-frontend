import {test,expect,login,api} from './fixtures'

test('award status and weekly processing persist',async({page,data})=>{
  await login(page,data)
  const created=await api(page,'/admin/rewards/awards/create/','POST',{name:`Weekly QA ${data.key}`,points_required:10,number_of_winners:1,award_period:'WEEKLY',status:'ACTIVE',is_active:true})
  expect(created.status).toBe(201)
  await page.goto('/admin/rewards/awards')
  await page.getByPlaceholder(/search/i).fill(`Weekly QA ${data.key}`)
  await page.getByRole('button',{name:'Deactivate',exact:true}).click()
  await expect(page.getByRole('button',{name:'Activate',exact:true})).toBeVisible()
  expect((await api(page,`/admin/rewards/awards/${created.body.id}/`)).body.is_active).toBe(false)
  await page.getByRole('button',{name:'Activate',exact:true}).click()
  await expect(page.getByRole('button',{name:'Deactivate',exact:true})).toBeVisible()
  await page.goto(`/admin/rewards/awards/${created.body.id}`)
  await page.getByRole('button',{name:'Process Weekly Award',exact:true}).click()
  await expect.poll(async()=> (await api(page,`/admin/rewards/awards/${created.body.id}/`)).body.status).toBe('COMPLETED')
  await page.reload()
  const awards=await api(page,`/admin/rewards/user-awards/?award_id=${created.body.id}`)
  expect((awards.body.results??awards.body).length).toBe(1)
})

